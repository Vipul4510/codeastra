@app.post(
    "/api/routes/plan",
    response_model=RoutePlanResponse,
    summary="Plan Route via OSRM",
    description="Calculates driving route between origin and destination coordinates using the OSRM Route API."
)
def plan_route(request: RoutePlanRequest):
    """
    Computes a route from origin to destination coordinates using OSRM Route API.
    Returns:
    - Origin and destination coordinates.
    - Route geometry as GeoJSON LineString.
    - Distance in metres and kilometres.
    - Baseline duration in seconds and minutes (free-flow; not live traffic).
    - Source and retrieval timestamp.
    - Route legs and steps if available.
    """
    service = get_route_service()
    try:
        return service.plan_route(
            origin_lat=request.origin.latitude,
            origin_lon=request.origin.longitude,
            dest_lat=request.destination.latitude,
            dest_lon=request.destination.longitude,
        )
    except CoordinateValidationError as e:
        raise HTTPException(status_code=400, detail=str(e))
    except RouteNotFoundError as e:
        raise HTTPException(status_code=404, detail=str(e))
    except OSRMTimeoutError as e:
        raise HTTPException(status_code=504, detail=str(e))
    except (OSRMServiceError, OSRMInvalidResponseError) as e:
        raise HTTPException(status_code=502, detail=str(e))
    except RoutingError as e:
        raise HTTPException(status_code=500, detail=str(e))

