@app.get(
    "/api/incidents/{incident_id}/route-impact",
    summary="Get Incident Route Impact",
    description="Returns incident details and its route-match explanation against optional journey coordinates or historical corridor context."
)
def get_incident_route_impact(
    incident_id: str,
    origin_lat: Optional[float] = Query(None, description="Optional journey origin latitude"),
    origin_lon: Optional[float] = Query(None, description="Optional journey origin longitude"),
    dest_lat: Optional[float] = Query(None, description="Optional journey destination latitude"),
    dest_lon: Optional[float] = Query(None, description="Optional journey destination longitude"),
):
    active_incidents = get_active_incidents(include_live=True, include_dataset=True)
    inc = next((i for i in active_incidents if i.incident_id == incident_id), None)
    if not inc:
        raise HTTPException(status_code=404, detail=f"Incident '{incident_id}' not found.")

    matching_service = get_route_matching_service()
    impact_match = None

    if origin_lat is not None and origin_lon is not None and dest_lat is not None and dest_lon is not None:
        try:
            route_svc = get_route_service()
            route_plan = route_svc.plan_route(origin_lat, origin_lon, dest_lat, dest_lon)
            impact_match = matching_service.match_incident(
                incident=inc,
                route_polyline=route_plan.geometry.coordinates,
                route_legs=route_plan.legs
            )
        except Exception as e:
            raise HTTPException(status_code=502, detail=f"Failed to evaluate journey route for incident: {str(e)}")

    return {
        "incident_id": inc.incident_id,
        "timestamp": inc.timestamp,
        "locality": inc.locality,
        "coordinates": {"latitude": inc.latitude, "longitude": inc.longitude},
        "status": inc.status,
        "alert_level": inc.alert_level,
        "passability": inc.passability,
        "speed_drop_pct": inc.speed_drop_pct,
        "delay_minutes": inc.delay_minutes,
        "affected_route_id": inc.affected_route_id,
        "is_road_blocked": inc.is_road_blocked,
        "route_impact_confidence": inc.route_impact_confidence,
        "evidence": inc.evidence,
        "nearby_assets": inc.nearby_assets,
        "root_cause_hypothesis": inc.root_cause_hypothesis,
        "journey_evaluation": impact_match.model_dump() if impact_match else None,
        "explanation": impact_match.explanation if impact_match else f"Incident {inc.incident_id} registered with status {inc.status} affecting corridor {inc.affected_route_id or 'localized'}."
    }

