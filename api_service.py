@app.post("/api/v1/telemetry")
def ingest_telemetry_and_evaluate(report: TelemetryReportInput):
    """
    Ingests live telemetry/report, evaluates relationships with ongoing events
    using the ML model, and immediately outputs the response plan for that location.
    """
    now_iso = datetime.now(timezone.utc).isoformat()
    evt_dict = {
        "observation_id": report.event_id or f"EVT-LIVE-{len(live_events)+1:05d}",
        "modality": report.source_modality,
        "event_type": report.event_type,
        "observation_time": report.timestamp_iso or now_iso,
        "latitude": report.latitude,
        "longitude": report.longitude,
        "locality": report.locality,
        "text": report.description_or_text,
        "water_level_cm": report.water_level_cm,
        "rainfall_rate_mm": report.rainfall_rate_mm,
        "pump_status": report.pump_status,
        "power_status": report.power_status
    }

    # 1. Evaluate with ML against recent events in the same locality
    latest_ml_eval = None
    if live_events:
        # Check against the most recent related or nearby event
        prior_evt = live_events[-1]
        try:
            latest_ml_eval = evaluate_pairwise_with_ml(evt_dict, prior_evt)
        except Exception as e:
            latest_ml_eval = {"error": str(e), "predicted_relationship": "INDETERMINATE", "confidence": 0.5}

    live_events.append(evt_dict)

    # 2. Find closest infrastructure assets
    nearest_assets = find_nearest_assets(report.latitude, report.longitude, top_k=3)

    # 3. Model & rule-driven response generation
    ml_rel = latest_ml_eval.get("predicted_relationship") if latest_ml_eval else "SINGLETON_INCIDENT"
    ml_conf = latest_ml_eval.get("confidence", 0.95) if latest_ml_eval else 0.95

    traffic_dict = report.traffic.model_dump() if report.traffic else {}

    response_plan = generate_location_response_plan(
        lat=report.latitude,
        lon=report.longitude,
        locality=report.locality,
        event_type=report.event_type,
        ml_relationship=ml_rel,
        ml_confidence=ml_conf,
        nearest_assets=nearest_assets,
        water_level_cm=report.water_level_cm,
        power_status=report.power_status,
        traffic_data=traffic_dict
    )

    # Enrich in-memory storage record with evaluated response, traffic, and metadata
    evt_dict["generated_response"] = response_plan
    evt_dict["model_evaluation"] = latest_ml_eval or {
        "predicted_relationship": "NEW_PRIMARY_INCIDENT",
        "confidence": 1.0,
        "note": "First incoming observation in active window"
    }
    evt_dict["traffic"] = traffic_dict
    evt_dict["nearby_assets"] = nearest_assets
    evt_dict["incident_id"] = evt_dict["observation_id"]
    evt_dict["status"] = "ACTIVE"
    evt_dict["provenance"] = report.source_modality

    return {
        "incident_id": evt_dict["observation_id"],
        "timestamp": evt_dict["observation_time"],
        "incident_location": {
            "locality": report.locality,
            "coordinates": {
                "latitude": report.latitude,
                "longitude": report.longitude
            },
            "nearby_critical_assets": nearest_assets
        },
        "model_evaluation": latest_ml_eval or {
            "predicted_relationship": "NEW_PRIMARY_INCIDENT",
            "confidence": 1.0,
            "note": "First incoming observation in active window"
        },
        "generated_response": response_plan
    }

@app.post("/api/v1/incident/response-by-location")
def query_response_for_location(query: IncidentLocationQuery):
    """
    Given a GPS location (lat, lon), evaluates all incidents happening in that vicinity,
    runs the ML relationship engine, and synthesizes the current response advisory.
    """
    nearby_reports = []
    for evt in live_events:
        d = haversine_km(query.latitude, query.longitude, evt["latitude"], evt["longitude"])
        if d <= query.radius_km:
            nearby_reports.append((d, evt))

    nearest_assets = find_nearest_assets(query.latitude, query.longitude, top_k=3)

    if not nearby_reports:
        return {
            "location": {
                "latitude": query.latitude,
                "longitude": query.longitude,
                "radius_km": query.radius_km
            },
            "status": "CLEAR",
            "incident_count": 0,
            "nearby_infrastructure": nearest_assets,
            "message": "No active incidents detected within this spatial radius."
        }

    nearby_reports.sort(key=lambda x: x[0])
    closest_dist, primary_event = nearby_reports[0]

    response_plan = generate_location_response_plan(
        lat=query.latitude,
        lon=query.longitude,
        locality=primary_event.get("locality", "Unknown Locality"),
        event_type=primary_event.get("event_type", "INCIDENT"),
        ml_relationship="CLUSTER_MEMBER",
        ml_confidence=0.91,
        nearest_assets=nearest_assets,
        water_level_cm=primary_event.get("water_level_cm"),
        power_status=primary_event.get("power_status")
    )

    return {
        "location": {
            "latitude": query.latitude,
            "longitude": query.longitude,
            "radius_km": query.radius_km
        },
        "status": "INCIDENT_ACTIVE",
        "incident_count": len(nearby_reports),
        "primary_incident": primary_event,
        "all_vicinity_events": [evt for _, evt in nearby_reports],
        "nearby_critical_assets": nearest_assets,
        "generated_response": response_plan
    }

